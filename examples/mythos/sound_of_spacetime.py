    def act7_morning(self):
        # Beat 61 — the date, stamped onto black
        headline(self, "SEPTEMBER 14, 2015", hold=0.2)

        # Beat 62 — the universe's copy settles over the prediction
        self.measured = ParametricFunction(
            lambda t: np.array([
                -6 + 12 * t,
                chirp_y(t) + 0.045 * np.sin(89 * t + 0.7) + 0.03 * np.sin(53 * t + 2.1),
                0,
            ]),
            t_range=[0, 1, 0.001], stroke_width=2)
        self.measured.set_stroke(IVORY, width=2, opacity=0.75)
        self.play(FadeIn(self.measured), run_time=2.2)

        # Beat 63
        caption(self, "The same curve — drawn this time by the universe.", hold=0.8)

        # Beat 64 — the number that pays off the c^4 charge
        strain = MathTex("h", "\\approx", "10^{-21}").scale(1.5).move_to([0, 0.6, 0])
        for part, col in zip(strain, [SKY, IVORY, SKY]):
            part.set_color(col)
        self.play(FadeIn(strain),
                  self.chirp.animate.set_stroke(opacity=0.25),
                  self.measured.animate.set_stroke(opacity=0.2), run_time=1.4)

        # Beat 65
        caption(self, "One part in a thousand billion billion.", color=SKY, hold=0.8)

        # Beat 66 — the strain cashes out into a ruler
        arm = MathTex("\\Delta L", "=", "h \\times L", "\\approx",
                      "4\\times 10^{-18}\\,\\mathrm{m}").scale(1.1).move_to(strain)
        for part, col in zip(arm, [OLIVE, IVORY, SKY, IVORY, OLIVE]):
            part.set_color(col)
        self.play(TransformMatchingTex(strain, arm), run_time=1.8)

        # Beat 67
        caption(self, "A thousandth of a proton, across four kilometers — and we felt it.",
                hold=1.0)

        # Beat 68 — the observatory at dawn: fabric above, voice below
        tilt = 50 * DEGREES
        monitor = RoundedRectangle(corner_radius=0.08, width=3.4, height=2.0,
                                   fill_color="#111110", fill_opacity=1.0,
                                   stroke_color=FOG, stroke_width=1.5)
        monitor.move_to([-1.8, -0.9, 0])
        mini = self.chirp.copy()
        mini.set_stroke(SKY, width=2, opacity=0.95)
        mini.scale(0.24).move_to(monitor.get_center())
        window = Rectangle(width=4.6, height=2.6, stroke_color=FOG, stroke_width=2)
        window.move_to([1.0, 0.5, 0])
        vig = VGroup(monitor, mini, window)
        vig.rotate(tilt, axis=RIGHT, about_point=ORIGIN)

        wc = _rx(np.array([1.0, 0.5, -0.35]), tilt)
        self.w_amp = ValueTracker(0.0)
        self.vig_fade = ValueTracker(0.0)

        def make_wgrid():
            a = self.w_amp.get_value()
            f = self.vig_fade.get_value()
            s = Surface(
                lambda u, v: np.array([0.55 * u, 0.28 * v,
                                       a * np.sin(1.5 * u) * np.cos(1.5 * v)]),
                u_range=[-2, 2], v_range=[-2, 2], resolution=(12, 12),
                fill_opacity=0.15 * f, checkerboard_colors=[DARK_A, DARK_B],
            )
            s.set_stroke(CORAL, width=0.8, opacity=0.5 * f)
            s.rotate(tilt, axis=RIGHT, about_point=ORIGIN)
            s.shift(wc)
            return s

        wgrid = always_redraw(make_wgrid)
        self.add(wgrid)
        cap = getattr(self, "_mythos_caption", None)
        extra = [FadeOut(cap)] if cap is not None else []
        self._mythos_caption = None
        self.move_camera(
            phi=tilt, theta=-90 * DEGREES, zoom=0.9, frame_center=ORIGIN, run_time=1.4,
            added_anims=[FadeOut(self.chirp), FadeOut(self.measured),
                         FadeOut(self.htl), FadeOut(arm), FadeIn(vig),
                         self.vig_fade.animate.set_value(1.0),
                         self.stars.animate.set_opacity(0.4)] + extra,
        )
        # the grid beyond the window trembles exactly once
        self.play(self.w_amp.animate.set_value(0.12), run_time=0.3)
        self.play(self.w_amp.animate.set_value(0.0), run_time=0.3)

        # Beat 69 — earned
        headline(self, "We heard spacetime sing.", hold=0.4)
        self.wait(0.1)
